import assert from 'node:assert/strict';
import {createDreadState,tickDread} from '../src/game/DreadDirector.js';
const state=createDreadState();
assert.equal(tickDread(state,.05,7.9),null);
assert.equal(tickDread(state,.05,8).kind,'settle');
assert.equal(tickDread(state,.05,10),null);
assert.equal(tickDread(state,.05,20).kind,'flicker');
assert.equal(state.dim,1,'light changes apply on subsequent frame');
tickDread(state,.05,20.05);
assert.ok(state.dim<1,'flicker should temporarily dim lights');
tickDread(state,.3,20.4);
assert.equal(state.dim,1,'light must recover after the cue');
const muted=createDreadState();
assert.equal(tickDread(muted,.05,8,{enemyNear:true}),null);
assert.equal(muted.index,1,'suppressed cues must not queue indefinitely');
const noPower=createDreadState();
tickDread(noPower,.05,8,{power:false});
assert.equal(tickDread(noPower,.05,20,{power:false}),null);
assert.equal(noPower.flicker,0,'cannot flicker unpowered lights');
const silence=createDreadState();
for(const time of [8,20,35])tickDread(silence,.05,time);
assert.equal(tickDread(silence,.05,44).kind,'silence');
assert.ok(silence.silence>3,'silence cue must have an audible duration');
tickDread(silence,3.6,47.6);
assert.equal(silence.silence,0,'silence must end without a stuck mute');
console.log('Dread pacing, threat suppression and power gating passed');
