import assert from 'node:assert/strict';
import {createDreadState,tickDread} from '../src/game/DreadDirector.js';
const state=createDreadState();
assert.equal(tickDread(state,.05,7.9),null);
assert.equal(tickDread(state,.05,8).kind,'settle');
assert.equal(tickDread(state,.05,10),null);
assert.equal(tickDread(state,.05,20).kind,'flicker');
tickDread(state,.05,20.05);
assert.ok(state.dim<1,'flicker temporarily dims lights');
tickDread(state,.3,20.4);
assert.equal(state.dim,1,'light recovers');
const suppressed=createDreadState();
assert.equal(tickDread(suppressed,.05,8,{enemyNear:true}),null);
assert.equal(suppressed.index,0,'threats defer instead of consuming cues');
const unpowered=createDreadState();
tickDread(unpowered,.05,8,{power:false});
assert.equal(tickDread(unpowered,.05,20,{power:false}),null);
assert.equal(unpowered.flicker,0);
const silence=createDreadState();
for(const t of [8,20,34])tickDread(silence,.05,t);
assert.equal(tickDread(silence,.05,48).kind,'silence');
assert.ok(silence.silence>4);
assert.equal(tickDread(silence,.05,50.5).kind,'quiet');
assert.equal(tickDread(silence,.05,51.9).kind,'settle');
tickDread(silence,5,57);
assert.equal(silence.silence,0);
const interrupted=createDreadState();
for(const t of [8,20,34,48])tickDread(interrupted,.05,t);
assert.ok(interrupted.sequence);
assert.equal(tickDread(interrupted,.05,49,{combat:true}),null);
assert.equal(interrupted.sequence,null);
assert.equal(interrupted.silence,0);
const alternate=createDreadState(1);
assert.notEqual(alternate.nextAt,state.nextAt);
console.log('Dread sequencing, pacing, suppression, variation and recovery passed');
