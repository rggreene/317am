import assert from 'node:assert/strict';
import {createNight,beginNight,tickNight,nightEvent,NIGHT_LENGTH,THREAT_DELAY,BARRICADE_DELAY,nearestInteractable} from '../src/game/SurvivalRules.js';
import {findNavigationPath,navigateStep} from '../src/game/NavGrid.js';
import {canOccupy} from '../src/game/CombatMath.js';
const s=createNight();
assert.equal(s.phase,'idle');
tickNight(s,1);
assert.equal(s.remaining,NIGHT_LENGTH);
beginNight(s);
assert.equal(nightEvent(s,'barricade'),true);
assert.equal(nightEvent(s,'barricade'),false);
assert.equal(nightEvent(s,'phone'),true);
for(let i=0;i<THREAT_DELAY*20;i++)tickNight(s,.05);
assert.equal(s.enemyEntered,false);
for(let i=0;i<BARRICADE_DELAY*20;i++)tickNight(s,.05);
assert.equal(s.enemyEntered,true);
assert.equal(nightEvent(s,'barricade'),false);
assert.equal(nightEvent(s,'hit'),true);
assert.equal(nightEvent(s,'hit'),false,'damage has cooldown');
assert.equal(s.health,84);
tickNight(s,1);
assert.equal(nightEvent(s,'medkit'),true);
assert.equal(s.health,100);
assert.equal(nightEvent(s,'medkit'),false);
while(s.phase==='playing')tickNight(s,.05);
assert.equal(s.phase,'won');
const noCall=createNight();beginNight(noCall);
while(noCall.phase==='playing')tickNight(noCall,.05);
assert.equal(noCall.phase,'lost');
const items=[{id:'phone',x:-2.70,z:1.48},{id:'door',x:2.72,z:2.11}];
assert.equal(nearestInteractable({x:-1.65,z:1.5},items)?.id,'phone');
assert.equal(nearestInteractable({x:0,z:0},items),null);
const route=findNavigationPath({x:2.73,z:2.12},{x:.05,z:1.70});
assert.ok(route.length>3,'enemy should find a path around the sofa');
assert.ok(route.every(p=>canOccupy(p.x,p.z)),'all route waypoints should be walkable');
let curr={x:2.73,z:2.12};
for(let step=0;step<800&&route.length;step++){
  const goal=route[0];curr=navigateStep(curr,goal,1,.05);
  if(Math.hypot(curr.x-goal.x,curr.z-goal.z)<.06)route.shift();
}
assert.equal(route.length,0,'route should be traversable');
console.log('Survival rules and enemy path tests passed');
